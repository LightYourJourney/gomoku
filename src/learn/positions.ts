import type { BoardSpec } from './types'

/** 字符画写成一行行字符串，读起来就是棋盘的样子。 */
export function board(...lines: string[]): BoardSpec {
  return { lines }
}

/** 空行，用来给棋盘留白。 */
export const BLANK = '...............'

/**
 * 一个反复用到的局面：黑棋横向是一条眠三——(4,7)(5,7)(6,7) 三颗子，
 * 两端各空一格、再外面各有一颗白子 ((2,7) 与 (8,7))，所以无论往哪头补都
 * 只能做成冲四；纵向 (7,5)(7,6) 还有两颗子，交点 (7,7) 空着。
 *
 * 落在交点上是一手**四三**——横向成冲四、纵向成活三，五手内强制取胜。
 * 它被 5 处内容共用：第 7 节讲四三、第 8 节讲这一手如何开启一条强制取胜
 * 路线（讲解页与练习各一处）、题库里的「四三」与「冲四开场」两道题。
 * **抄五遍的话改一处必漏四处**，所以放在这里。
 *
 * **那两颗白子不是配平的摆设，是结构本身**：挪掉 (8,7) 那颗，横向就从
 * 「补一格成冲四」变成「补一格成活四」，这道题的答案与讲解全部作废。
 * 改这个局面时白子一颗都不能动。
 */
export const FOUR_THREE = board(
  BLANK,
  '.....W.........',
  BLANK,
  BLANK,
  '.......B.......',
  '.......B.......',
  BLANK,
  '..W.BBB.W......',
  BLANK,
  BLANK,
  '....W..........',
  BLANK,
  '..........W....',
  BLANK,
  BLANK,
)
